param([Parameter(Mandatory)][string]$Candidate)
$ErrorActionPreference = 'Stop'
$workspace = '<WORKSPACE>'
$mo2 = '<MO2>'
$gameData = '<GAME>\Data'
$candidatePath = [IO.Path]::GetFullPath($Candidate)
if (-not $candidatePath.StartsWith((Join-Path $workspace 'outgoing\meridian-test-'), [StringComparison]::OrdinalIgnoreCase)) { throw 'Candidate must be a workspace test artifact' }
& (Join-Path $workspace 'plans\test-meridian-candidate.ps1') -Candidate $candidatePath | Out-Null
if (Get-Process SkyrimSE,ModOrganizer -ErrorAction SilentlyContinue) { throw 'Close the game and MO2 before preparing isolated profiles' }
if (-not (Test-Path -LiteralPath (Join-Path $mo2 'ModOrganizer.ini'))) { throw 'Selected MO2 instance missing' }
$runId = Split-Path -Leaf $candidatePath
$suffix = $runId.Replace('meridian-test-','')
$modName = "Aetherius - Meridian - TESTE - $suffix"
$modTarget = Join-Path $mo2 "mods\$modName"
$profileFiles = @('archives.txt','initweaks.ini','loadorder.txt','lockedorder.txt','modlist.txt','plugins.txt','settings.ini')
$profiles = @(
  [pscustomobject]@{source='AETHERIUS - GRAFICO - QUALIDADE'; name="TESTE MERIDIAN - MINIMO - $suffix"; minimal=$true},
  [pscustomobject]@{source='AETHERIUS - GRAFICO - QUALIDADE'; name="TESTE MERIDIAN - QUALIDADE - $suffix"; minimal=$false},
  [pscustomobject]@{source='AETHERIUS - PERFORMANCE'; name="TESTE MERIDIAN - PERFORMANCE - $suffix"; minimal=$false}
)
# Validate every new target BEFORE any write. Never overwrite an existing mod/profile.
foreach ($target in @($modTarget) + @($profiles | ForEach-Object { Join-Path $mo2 "profiles\$($_.name)" })) {
  $absolute = [IO.Path]::GetFullPath($target)
  if (-not $absolute.StartsWith($mo2 + '\', [StringComparison]::OrdinalIgnoreCase)) { throw 'Target escapes selected MO2' }
  if (Test-Path -LiteralPath $absolute) { throw "Existing target, refusing overwrite: $absolute" }
}
foreach ($source in @($profiles.source | Sort-Object -Unique)) {
  foreach ($file in $profileFiles) {
    if (-not (Test-Path -LiteralPath (Join-Path $mo2 "profiles\$source\$file"))) { throw "Missing source profile file: $source/$file" }
  }
}
$manifest = Get-Content -LiteralPath (Join-Path $candidatePath 'manifest.json') -Raw | ConvertFrom-Json
$protectedPaths = @(
  (Join-Path $mo2 'ModOrganizer.ini')
  foreach ($source in @($profiles.source | Sort-Object -Unique)) {
    foreach ($file in $profileFiles) { Join-Path $mo2 "profiles\$source\$file" }
  }
  foreach ($entry in $manifest.entries) { Join-Path $gameData $entry.path }
  '<MO2>\mods\AETHERIUS - OVERWRITE\SKSE\Plugins\SkyrimPlatform.ini'
)
$before = @($protectedPaths | ForEach-Object {
  [pscustomobject]@{path=$_; existed=(Test-Path -LiteralPath $_); sha256=if (Test-Path -LiteralPath $_) {(Get-FileHash -LiteralPath $_).Hash} else {$null}}
})
New-Item -ItemType Directory -Path $modTarget | Out-Null
Copy-Item -LiteralPath (Join-Path $candidatePath 'Aetherius - Meridian - TESTE\SKSE'), (Join-Path $candidatePath 'Aetherius - Meridian - TESTE\Platform'), (Join-Path $candidatePath 'Aetherius - Meridian - TESTE\MeridianUI') -Destination $modTarget -Recurse
$minimalMods = @('Meridian UI - GPU Rendered User Interface for Skyrim - DLSS 5 Support','Address Library for SKSE Plugins')
foreach ($profile in $profiles) {
  $target = Join-Path $mo2 "profiles\$($profile.name)"
  New-Item -ItemType Directory -Path $target | Out-Null
  foreach ($file in $profileFiles) { Copy-Item -LiteralPath (Join-Path $mo2 "profiles\$($profile.source)\$file") -Destination (Join-Path $target $file) }
  $modlist = @(Get-Content -LiteralPath (Join-Path $target 'modlist.txt'))
  if ($profile.minimal) {
    $modlist = @($modlist | ForEach-Object {
      if ($_ -match '^[+-](.+)$') {
        if ($Matches[1] -in $minimalMods) { '+' + $Matches[1] } else { '-' + $Matches[1] }
      } else { $_ }
    })
    foreach ($mod in $minimalMods) { if (('+' + $mod) -notin $modlist) { throw "Minimal dependency absent: $mod" } }
    # Keep only existing implicit masters / CC files, never gameplay/generated plugins.
    $loadorder = @(Get-Content -LiteralPath (Join-Path $target 'loadorder.txt') | Where-Object {
      $_.StartsWith('#') -or $_ -in @('Skyrim.esm','Update.esm','Dawnguard.esm','HearthFires.esm','Dragonborn.esm','_ResourcePack.esl') -or $_ -match '^cc.+\.(esm|esl)$'
    })
    $loadorder | Set-Content -LiteralPath (Join-Path $target 'loadorder.txt') -Encoding utf8NoBOM
    '# This file was automatically generated by Mod Organizer.' | Set-Content -LiteralPath (Join-Path $target 'plugins.txt') -Encoding utf8NoBOM
    '# This file was automatically generated by Mod Organizer.' | Set-Content -LiteralPath (Join-Path $target 'lockedorder.txt') -Encoding utf8NoBOM
  }
  # MO2 stores modlist in descending priority; first mod after header wins.
  @($modlist[0]; ('+' + $modName); $modlist[1..($modlist.Count - 1)]) | Set-Content -LiteralPath (Join-Path $target 'modlist.txt') -Encoding utf8NoBOM
  $settings = Get-Content -LiteralPath (Join-Path $target 'settings.ini') -Raw
  if ($settings -notmatch '(?m)^LocalSaves=false\r?$') { throw 'Unexpected source LocalSaves setting' }
  # No production saves are copied or shown in the test profile.
  $settings -replace '(?m)^LocalSaves=false\r?$', 'LocalSaves=true' | Set-Content -LiteralPath (Join-Path $target 'settings.ini') -Encoding utf8NoBOM
}
foreach ($entry in $manifest.entries) {
  if ((Get-FileHash -LiteralPath (Join-Path $modTarget $entry.path)).Hash -ne $entry.sha256) { throw "Installed test file mismatch: $($entry.path)" }
}
foreach ($row in $before) {
  if ((Test-Path -LiteralPath $row.path) -ne $row.existed) { throw "Protected path changed: $($row.path)" }
  if ($row.existed -and (Get-FileHash -LiteralPath $row.path).Hash -ne $row.sha256) { throw "Protected file modified: $($row.path)" }
}
[pscustomobject]@{
  status='TEST ONLY - NOT HOMOLOGATED'; createdUtc=[DateTime]::UtcNow.ToString('o'); instance=$mo2
  modName=$modName; modTarget=$modTarget; profiles=$profiles; protectedFiles=$before
  protectedFilesUnchanged=$true; activeProfileChanged=$false; gameStarted=$false; release='none'
  minimalScope='Only two MO2 dependencies plus test overlay enabled; existing base-game Data (including MpClientPlugin) remains. This is not a clean game installation.'
} | ConvertTo-Json -Depth 6 | Set-Content -LiteralPath (Join-Path $candidatePath 'deployment.json') -Encoding utf8
Write-Output "INSTALLED TEST MOD: $modTarget"
$profiles | ForEach-Object { Write-Output "CREATED TEST PROFILE: $($_.name)" }
Write-Output 'Official profiles, active profile and game Data unchanged; game NOT started.'

